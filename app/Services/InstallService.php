<?php
declare(strict_types=1);

namespace App\Services;

defined('NX_ROOT') || exit;

use App\Core\App;
use App\Core\Crypto;
use App\Core\DB;
use App\Core\Schema;

final class InstallService
{
    public static function requirements(): array
    {
        $m = App::manifest();
        $req = $m['requirements'] ?? [];
        $checks = [];
        $minPhp = (string) ($req['php'] ?? '8.2.0');
        $checks[] = ['group' => 'PHP', 'label' => 'PHP version ' . $minPhp . '+', 'ok' => version_compare(PHP_VERSION, $minPhp, '>='), 'value' => PHP_VERSION, 'required' => true];
        foreach ((array) ($req['extensions'] ?? []) as $ext) {
            $checks[] = ['group' => 'Extensions', 'label' => $ext, 'ok' => extension_loaded($ext), 'value' => extension_loaded($ext) ? 'Loaded' : 'Missing', 'required' => true];
        }
        foreach ((array) ($req['optional_extensions'] ?? []) as $ext => $why) {
            $checks[] = ['group' => 'Optional', 'label' => $ext . ' — ' . $why, 'ok' => extension_loaded($ext), 'value' => extension_loaded($ext) ? 'Loaded' : 'Not loaded', 'required' => false];
        }
        $checks[] = ['group' => 'PHP', 'label' => 'Argon2id password hashing', 'ok' => defined('PASSWORD_ARGON2ID'), 'value' => defined('PASSWORD_ARGON2ID') ? 'Available' : 'Falls back to bcrypt', 'required' => false];
        $checks[] = ['group' => 'PHP', 'label' => 'memory_limit ≥ 128M', 'ok' => self::bytes((string) ini_get('memory_limit')) >= 128 * 1048576 || ini_get('memory_limit') === '-1', 'value' => (string) ini_get('memory_limit'), 'required' => false];
        $checks[] = ['group' => 'PHP', 'label' => 'upload_max_filesize', 'ok' => true, 'value' => (string) ini_get('upload_max_filesize'), 'required' => false];
        foreach (['config', 'storage', 'storage/uploads', 'storage/logs', 'storage/cache', 'storage/tmp', 'storage/backups', 'storage/sessions'] as $dir) {
            $path = NX_ROOT . '/' . $dir;
            if (!is_dir($path)) {
                @mkdir($path, 0750, true);
            }
            $checks[] = ['group' => 'Folders', 'label' => $dir . '/ writable', 'ok' => is_dir($path) && is_writable($path), 'value' => is_writable($path) ? 'Writable' : 'Not writable', 'required' => true];
        }
        $checks[] = ['group' => 'Server', 'label' => 'URL rewriting (.htaccess)', 'ok' => is_file(NX_ROOT . '/.htaccess'), 'value' => is_file(NX_ROOT . '/.htaccess') ? 'Present' : 'Missing .htaccess', 'required' => false];
        return $checks;
    }

    private static function bytes(string $v): int
    {
        $n = (int) $v;
        return match (strtoupper(substr(trim($v), -1))) { 'G' => $n * 1073741824, 'M' => $n * 1048576, 'K' => $n * 1024, default => $n };
    }

    /** @return array{0:bool,1:string} */
    public static function testDatabase(array $cfg): array
    {
        try {
            $db = new DB($cfg);
            if ($db->driver === 'sqlite') {
                return [true, 'SQLite connection OK (testing mode).'];
            }
            $version = (string) $db->value('SELECT VERSION()');
            $isMaria = stripos($version, 'mariadb') !== false;
            $num = preg_replace('/[^0-9.].*$/', '', $version) ?? '0';
            if ($isMaria ? version_compare($num, '10.6', '<') : version_compare($num, '8.0', '<')) {
                return [false, "Database version $version is too old. MySQL 8.0+ or MariaDB 10.6+ is required."];
            }
            $tables = (int) $db->value('SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE()');
            $db->pdo->exec('CREATE TABLE IF NOT EXISTS `nx_install_probe` (`id` INT PRIMARY KEY) ENGINE=InnoDB');
            $db->pdo->exec('CREATE INDEX `ix_probe` ON `nx_install_probe` (`id`)');
            $db->pdo->exec('DROP TABLE `nx_install_probe`');
            $note = $tables > 0 ? " Note: the database already contains $tables table(s); existing NextaCRM tables will be reused." : '';
            return [true, "Connected to $version. CREATE/INDEX/DROP privileges confirmed.$note"];
        } catch (\Throwable $e) {
            $msg = $e->getMessage();
            $msg = preg_replace('/\(using password: (YES|NO)\)/', '', $msg) ?? $msg;
            return [false, 'Connection failed: ' . $msg];
        }
    }

    public static function writeConfig(array $config): void
    {
        $php = "<?php\n// NextaCRM configuration — generated by the installer on " . gmdate('Y-m-d H:i') . " UTC.\n// Keep this file private. It is protected by config/.htaccess.\ndefined('NX_ROOT') || exit;\nreturn " . var_export($config, true) . ";\n";
        $file = NX_ROOT . '/config/config.php';
        if (!is_dir(dirname($file))) {
            mkdir(dirname($file), 0750, true);
        }
        if (file_put_contents($file, $php, LOCK_EX) === false) {
            throw new \RuntimeException('Could not write config/config.php. Make the config folder writable.');
        }
        @chmod($file, 0640);
        @file_put_contents(NX_ROOT . '/config/.htaccess', "Require all denied\nDeny from all\n");
    }

    public static function migrate(DB $db): void
    {
        $schema = Schema::load();
        foreach ($schema->compile($db->driver) as $sql) {
            try {
                $db->pdo->exec($sql);
            } catch (\PDOException $e) {
                // Duplicate index on re-run is harmless (MySQL has no CREATE INDEX IF NOT EXISTS).
                if (!str_contains($e->getMessage(), 'Duplicate key name') && !str_contains($e->getMessage(), 'already exists')) {
                    throw $e;
                }
            }
        }
        foreach (Migrator::available() as $name) {
            if (!$db->value('SELECT id FROM migrations WHERE name = ?', [$name])) {
                $db->insert('migrations', ['name' => $name, 'ran_at' => DB::now()]);
            }
        }
    }

    /**
     * Full installation. $data: db config, url, admin{name,email,password}, company{name,currency,timezone,country}, demo bool.
     */
    public static function install(array $data): void
    {
        $dbCfg = $data['db'];
        $db = new DB($dbCfg);
        App::setDb($db);
        $config = [
            'app_key' => Crypto::generateKey(),
            'url' => rtrim((string) $data['url'], '/'),
            'db' => $dbCfg,
            'timezone' => $data['company']['timezone'] ?? 'UTC',
            'locale' => 'en',
            'debug' => false,
            'force_https' => str_starts_with((string) $data['url'], 'https://') && PHP_SAPI !== 'cli' && App::request()->isSecure(),
            'trusted_proxies' => [],
            'installed_at' => gmdate('c'),
            'installed_version' => App::version(),
        ];
        App::setConfig($config);
        self::migrate($db);
        Seeder::run($db, $data);
        self::writeConfig($config);
        @file_put_contents(NX_ROOT . '/storage/installed.lock', json_encode(['installed_at' => gmdate('c'), 'version' => App::version()]));
        foreach (['storage', 'storage/uploads', 'storage/logs', 'storage/backups', 'storage/tmp', 'storage/sessions', 'storage/cache', 'vendor', 'app'] as $d) {
            if (is_dir(NX_ROOT . '/' . $d) && !is_file(NX_ROOT . '/' . $d . '/.htaccess')) {
                @file_put_contents(NX_ROOT . '/' . $d . '/.htaccess', "Require all denied\nDeny from all\n");
            }
        }
    }
}
